GLYPHS = {char: rows.split() for char, rows in _RAW.items()}
for _char, _rows in GLYPHS.items():
    assert len(_rows) == HEIGHT and len({len(r) for r in _rows}) == 1, _char


def glyph(char):
    return GLYPHS.get(char.upper(), GLYPHS["?"])


def text_width(text, sx=1, gap=None):
    """Largeur en pixels de `text` à l'échelle horizontale `sx`.

    `gap` : espace entre lettres en pixels (par défaut `sx`)."""
    if not text:
        return 0
    gap = sx if gap is None else gap
    return sum(len(glyph(c)[0]) for c in text) * sx + (len(text) - 1) * gap


def draw_text(pixels, x, y, text, color, sx=1, sy=1, gap=None, size=None):
    """Dessine `text` dans un accès pixel PIL (`image.load()`)."""
    width, height = size
    gap = sx if gap is None else gap
    for char in text:
        rows = glyph(char)
        for row_index, row in enumerate(rows):
            for col_index, cell in enumerate(row):
                if cell != "#":
                    continue
                for dx in range(sx):
                    for dy in range(sy):
                        px = x + col_index * sx + dx
                        py = y + row_index * sy + dy
                        if 0 <= px < width and 0 <= py < height:
                            pixels[px, py] = color
        x += len(rows[0]) * sx + gap
    return x
